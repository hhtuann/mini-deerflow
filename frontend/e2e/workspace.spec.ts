test('real offline research: skill, follow-up, persistence, safe inspector and phone keyboard', async ({ page, request }, testInfo) => {
  const browserErrors: string[] = [];
  page.on('pageerror', (error) => { browserErrors.push(error.message); console.error(error); });
  await page.setViewportSize({ width: 1440, height: 900 });
  // The launcher starts with a new storage directory and does not seed any DB.
  const initialHistory = await request.get('/api/offline/conversations');
  expect(initialHistory.status()).toBe(200);
  expect(await initialHistory.json()).toEqual([]);
  expect(await (await request.get('/api/offline/jobs')).json()).toEqual([]);
  await page.goto('/?mode=offline');
  await expect(page.getByLabel('Your research question')).toBeEnabled();
  await page.getByLabel('Skill for next turn').selectOption('research-brief');
  await expect(page.getByText(/Applicability:/)).toBeVisible();
  await page.getByLabel('Your research question').fill('Compare reliable evidence about this research topic.');
  const submitted = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().endsWith('/api/offline/conversations'));
  await page.getByRole('button', { name: 'Send message' }).click();
  const firstJob = await (await submitted).json() as JobDTO;
  const path = `/api/offline/conversations/${firstJob.thread_id}`;
  await expect.poll(async () => (await (await request.get(`/api/offline/jobs/${firstJob.job_id}`)).json() as JobDTO).status).toBe('completed');
  await expect(page.getByLabel('Ask a follow-up')).toBeEnabled();
  await expect(page.getByLabel('Skill for next turn')).toHaveValue('');
  await expect(page.getByRole('article', { name: 'Turn 1', exact: true }).getByText('research-brief', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('desktop-chat.png'), fullPage: true });
  await page.getByLabel('Ask a follow-up').fill('What are the limitations of the collected evidence?');
  const followup = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().endsWith(`${path}/turns`));
  await page.getByRole('button', { name: 'Send message' }).click();
  const followupJob = await (await followup).json() as JobDTO;
  await expect.poll(async () => (await (await request.get(`/api/offline/jobs/${followupJob.job_id}`)).json() as JobDTO).status).toBe('completed');
  await page.reload();
  await expect(page.getByRole('article', { name: 'Turn 2', exact: true })).toBeVisible();
  await expect(page.getByRole('article', { name: 'Turn 2', exact: true }).getByText('None', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Inspect turn 1', exact: true }).click();
  await expect(page.getByLabel('Inspect turn')).toHaveValue(firstJob.turn_id!);
  // Genuine pointer + keyboard interactions against the running React/FastAPI app.
  // This checks CSS grid sizing; unit-only width calculations cannot prove the UI.
  const resizeHandle = page.getByRole('separator', { name: 'Resize execution inspector' });
  const inspectorPane = page.locator('.desktop-inspector');
  await expect(resizeHandle).toHaveAttribute('aria-valuenow', '400');
  for (const viewport of [1280, 1366, 1440, 1920]) {
    await page.setViewportSize({ width: viewport, height: 900 });
    await expect(inspectorPane).toBeVisible();
    const maxWidth = viewport - 250 - 380;
    await resizeHandle.focus();
    await page.keyboard.press('End');
    await expect(resizeHandle).toHaveAttribute('aria-valuenow', String(maxWidth));
    expect(Math.abs((await inspectorPane.boundingBox())!.width - maxWidth)).toBeLessThanOrEqual(1);
    const handleBox = await resizeHandle.boundingBox();
    expect(handleBox).toBeTruthy();
    const startX = handleBox!.x + handleBox!.width / 2;
    const startY = Math.max(50, handleBox!.y + 90);
    await page.mouse.move(startX, startY);
    await page.mouse.down();
    await page.mouse.move(startX + 120, startY, { steps: 8 });
    await page.mouse.up();
    await expect(resizeHandle).toHaveAttribute('aria-valuenow', String(maxWidth - 120));
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath(`inspector-resized-${viewport}.png`), fullPage: true });
    await resizeHandle.focus();
    await page.keyboard.press('Home');
    await expect(resizeHandle).toHaveAttribute('aria-valuenow', '340');
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await resizeHandle.focus();
  await page.keyboard.press('ArrowLeft');
  await expect(resizeHandle).toHaveAttribute('aria-valuenow', '364');
  await page.keyboard.press('ArrowRight');
  await expect(resizeHandle).toHaveAttribute('aria-valuenow', '340');
  // Collapsing conversation navigation allows Inspector to grow further.
  await page.getByRole('button', { name: 'Collapse sidebar' }).click();
  await resizeHandle.focus();
  await page.keyboard.press('End');
  await expect(resizeHandle).toHaveAttribute('aria-valuenow', String(1440 - 380));
  await page.getByRole('button', { name: 'Expand sidebar' }).click();
  await expect(resizeHandle).toHaveAttribute('aria-valuenow', String(1440 - 250 - 380));
  await page.keyboard.press('Home');
  const data = await (await request.get(path)).json() as ChatSession;
  const run = data.turns[0].run!;
  for (const [label, value] of [['Nodes', run.execution_graph.metrics.nodes], ['Running', run.execution_graph.metrics.running], ['Completed', run.execution_graph.metrics.completed], ['Failed', run.execution_graph.metrics.failed], ['Tool calls', run.execution_graph.metrics.tool_calls], ['Sub-agents', run.execution_graph.metrics.sub_agents], ['Evidence', run.execution_graph.metrics.evidence]] as const) {
    await expect(page.locator('.graph-metrics > div').filter({ has: page.getByText(label, { exact: true }) }).locator('dd')).toHaveText(String(value));
  }
  await expect(page.getByRole('list', { name: 'Node statuses' }).getByRole('listitem')).toHaveCount(6);
  await expect(page.getByRole('list', { name: 'Node kinds' }).getByRole('listitem')).toHaveCount(6);
  const failed = run.execution_graph.nodes.find((node) => node.kind === 'branch' && node.status === 'failed')!;
  expect(failed).toBeTruthy();
  await page.getByLabel('Inspect node').selectOption(failed.id);
  const details = page.getByRole('region', { name: 'Node details' });
  await expect(details.locator('.status-failed')).toContainText('failed');
  await details.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('desktop-failed-child-graph.png'), fullPage: true });
  const parent = run.execution_graph.nodes.find((node) => node.kind === 'run' && node.status === 'completed')!;
  // Exercise the actual canvas click path, independently of the native selector.
  const parentCanvasNode = page.locator('.react-flow__node').filter({ has: page.getByText(parent.label, { exact: true }) });
  await parentCanvasNode.click();
  await expect(page.getByLabel('Inspect node')).toHaveValue(parent.id);
  await expect(details.getByRole('heading', { name: parent.label })).toBeVisible();
  for (const kind of ['fan_in', 'branch', 'workflow_node']) {
    const node = run.execution_graph.nodes.find((item) => item.kind === kind && item.status === 'completed');
    expect(node).toBeTruthy();
    await page.getByLabel('Inspect node').selectOption(node!.id);
    await expect(details.getByRole('heading', { name: node!.label })).toBeVisible();
  }
  const continuation = run.execution_graph.edges.find((edge) => edge.relation === 'parent_continues');
  expect(continuation).toBeTruthy();
  await page.getByLabel('Inspect node').selectOption(continuation!.target);
  await expect(details).toBeVisible();
  await page.getByLabel('Graph view').selectOption('Workflow');
  await expect(page.getByRole('tabpanel')).toContainText('Possible topology only');
  await expect(page.getByLabel('Inspect node')).toContainText('Planner');
  await page.getByLabel('Graph view').selectOption('Current run');
  await page.getByRole('tab', { name: 'Evidence', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText(run.evidence[0].title);
  await page.getByRole('tab', { name: 'Trace', exact: true }).click();
  const kind = run.traces[0].kind;
  await page.getByRole('listbox', { name: 'Kind', exact: true }).selectOption(kind);
  await expect(page.getByRole('tabpanel')).toContainText(`${run.traces.filter((event) => event.kind === kind).length} of ${run.traces.length} events`);
  const selectedRuns = [...new Set(run.traces.map((event) => event.run_id))].slice(0, 2);
  const selectedKinds = ['tool', 'branch'];
  const selectedOutcomes = ['succeeded', 'failed'];
  await page.getByRole('listbox', { name: 'Run', exact: true }).selectOption(selectedRuns);
  await page.getByRole('listbox', { name: 'Kind', exact: true }).selectOption(selectedKinds);
  await page.getByRole('listbox', { name: 'Outcome', exact: true }).selectOption(selectedOutcomes);
  const filtered = run.traces.filter((event) => selectedRuns.includes(event.run_id) && selectedKinds.includes(event.kind) && selectedOutcomes.includes(event.outcome));
  expect(filtered.length).toBeGreaterThan(0);
  expect(filtered.length).toBeLessThan(run.traces.length);
  await expect(page.getByRole('tabpanel')).toContainText(`${filtered.length} of ${run.traces.length} events`);
  await page.getByRole('button', { name: 'Reset trace filters', exact: true }).click();
  await expect(page.getByRole('listbox', { name: 'Run', exact: true })).toHaveValues([]);
  await expect(page.getByRole('listbox', { name: 'Kind', exact: true })).toHaveValues([]);
  await expect(page.getByRole('listbox', { name: 'Outcome', exact: true })).toHaveValues([]);
  await expect(page.getByRole('tabpanel')).toContainText(`${run.traces.length} of ${run.traces.length} events`);
  await page.getByRole('tab', { name: 'Plan', exact: true }).click();
  await expect(page.getByRole('tabpanel').getByRole('heading', { name: 'Goal', exact: true })).toBeVisible();
  await expect(page.getByRole('tabpanel')).toContainText(run.goal);
  await page.getByRole('tab', { name: 'Context', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText('approximate');
  await page.screenshot({ path: testInfo.outputPath('desktop-context.png'), fullPage: true });
  await page.getByRole('tab', { name: 'Artifacts', exact: true }).click();
  await expect(page.getByTestId('artifact-source')).toHaveText(run.artifact.markdown_source);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download Markdown' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('report.md');
  const artifactResponse = await request.get(`${path}/turns/${firstJob.turn_id}/artifact`);
  expect(await artifactResponse.text()).toBe(run.artifact.markdown_source);
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await expect(page.getByRole('dialog', { name: 'Navigation' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Open navigation' })).toBeFocused();
  await page.getByRole('button', { name: 'Open execution inspector' }).click();
  const dialog = page.getByRole('dialog', { name: 'Execution inspector' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByLabel('Inspect node')).toBeVisible();
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('phone-graph-inspector.png') });
  await dialog.getByRole('tab', { name: 'Graph', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(dialog.getByRole('tab', { name: 'Plan', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(dialog.getByRole('tab', { name: 'Plan', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Open execution inspector' })).toBeFocused();
  const composer = page.getByLabel('Ask a follow-up');
  await expect(composer).toBeEnabled();
  await composer.focus();
  await expect(composer).toBeFocused();
  await composer.pressSequentially('Compare the limitations from this phone-sized workspace.');
  await expect(composer).toBeInViewport({ ratio: 1 });
  await expect(page.getByRole('button', { name: 'Send message' })).toBeInViewport({ ratio: 1 });
  const phoneSubmission = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().endsWith(`${path}/turns`));
  await composer.press('Enter');
  const phoneResponse = await phoneSubmission;
  expect(phoneResponse.status()).toBe(202);
  const phoneJob = await phoneResponse.json() as JobDTO;
  await expect.poll(async () => (await (await request.get(`/api/offline/jobs/${phoneJob.job_id}`)).json() as JobDTO).status).toBe('completed');
  await expect(composer).toBeEnabled();
  await expect(page.getByRole('article', { name: 'Turn 3', exact: true })).toContainText('Compare the limitations from this phone-sized workspace.');
  await expect(composer).toBeInViewport({ ratio: 1 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('phone-workspace.png'), fullPage: true });
  expect(browserErrors).toEqual([]);
});

test('restored interruption resumes the same turn; offline mode identity and read errors recover', async ({ page, request, context }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  // Seed only after the cold-storage workflow has run. This command uses the
  // real offline runtime against the launcher's isolated storage, with no API mocks.
  execFileSync('uv', ['run', 'python', 'frontend/e2e/serve_api.py', '--seed-interrupted'], { cwd: fileURLToPath(new URL('../../', import.meta.url)), env: process.env });
  const path = '/api/offline/conversations/browser-interrupted';
  const before = await (await request.get(path)).json() as ChatSession;
  expect(before.turns[0].status).toBe('interrupted');
  await page.goto('/?mode=offline&thread=browser-interrupted');
  await expect(page.getByRole('button', { name: 'Resume active turn' })).toBeVisible();
  await expect(page.getByLabel('Ask a follow-up')).toBeDisabled();
  await page.reload();
  const response = page.waitForResponse((item) => item.request().method() === 'POST' && item.url().endsWith(`${path}/resume`));
  await page.getByRole('button', { name: 'Resume active turn' }).click();
  const resumed = await (await response).json() as JobDTO;
  expect(resumed.turn_id).toBe(before.turns[0].turn_id);
  await expect.poll(async () => (await (await request.get(`/api/offline/jobs/${resumed.job_id}`)).json() as JobDTO).status).toBe('completed');
  await expect(page.getByLabel('Ask a follow-up')).toBeEnabled();
  await page.reload();
  await expect(page.getByRole('article')).toHaveCount(1);
  await expect(page.getByRole('article').getByText('research-brief', { exact: true })).toBeVisible();
  const after = await (await request.get(path)).json() as ChatSession;
  expect(after.turns[0].turn_id).toBe(before.turns[0].turn_id);
  expect(after.turns[0].status).toBe('completed');
  const persisted = after.turns[0].run!;
  const terminalJob = await (await request.get(`/api/offline/jobs/${resumed.job_id}`)).json() as JobDTO;
  expect(terminalJob.traces.some((event) => event.kind === 'tool')).toBe(false);
  expect(persisted.traces.length).toBeGreaterThan(terminalJob.traces.length);
  await page.getByRole('button', { name: 'Inspect turn 1', exact: true }).click();
  await expect(page.getByLabel('Graph view')).toHaveValue('Current run');
  for (const [kind, status] of [['branch', 'failed'], ['branch', 'completed'], ['delegation', 'completed'], ['fan_in', 'completed']] as const) {
    const priorNode = before.turns[0].run!.execution_graph.nodes.find((node) => node.kind === kind && node.status === status);
    expect(priorNode, `${kind} ${status} must exist before resume`).toBeTruthy();
    await page.getByLabel('Inspect node').selectOption(priorNode!.id);
    const details = page.getByRole('region', { name: 'Node details' });
    await expect(details.getByRole('heading', { name: priorNode!.label })).toBeVisible();
    await expect(details.locator(`.status-${status}`)).toContainText(status);
  }
  await page.getByRole('tab', { name: 'Tools & Delegation', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText('Fan-in: 1 successful · 1 failed');
  const priorTool = before.turns[0].run!.traces.find((event) => event.tool_name)!.tool_name!;
  await expect(page.getByRole('tabpanel')).toContainText(priorTool);
  await page.getByRole('tab', { name: 'Trace', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText(`${persisted.traces.length} of ${persisted.traces.length} events`);
  await page.getByRole('listbox', { name: 'Kind', exact: true }).selectOption('tool');
  const toolTraces = persisted.traces.filter((event) => event.kind === 'tool');
  expect(toolTraces.length).toBeGreaterThan(0);
  await expect(page.getByRole('tabpanel')).toContainText(`${toolTraces.length} of ${persisted.traces.length} events`);
  await page.screenshot({ path: testInfo.outputPath('resumed-persisted-turn.png') });
  await page.getByRole('combobox', { name: 'Execution mode' }).selectOption('live');
  await expect(page.getByText('LIVE RESEARCH')).toBeVisible();
  await expect(page.getByRole('article')).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Execution mode' }).selectOption('offline');
  await expect(page.getByRole('button', { name: /Resume this interrupted evidence comparison/ })).toBeVisible();
  await context.setOffline(true);
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send message' })).toBeDisabled();
  await context.setOffline(false);
  await page.getByRole('button', { name: 'Refresh workspace' }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await expect(page.getByLabel('Your research question')).toBeEnabled();
});
