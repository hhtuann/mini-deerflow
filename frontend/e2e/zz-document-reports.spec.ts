import { expect, test } from '@playwright/test';

test('grounded reports retain immutable history and untouched approved sections', async ({ request }) => {
  const workspace = await request.post('/api/offline/workspaces', { data: { name: 'Synthetic report workspace' } });
  expect(workspace.status()).toBe(201);
  const ws = (await workspace.json()).workspace_id;
  const base = `/api/offline/workspaces/${ws}`;
  const uploaded = await request.post(`${base}/documents?filename=fixture.txt`, { data: Buffer.from('Revenue is 10 synthetic credits.\n\nCost is 4 synthetic credits.'), headers: { 'Content-Type': 'text/plain' } });
  expect(uploaded.status()).toBe(201);
  const doc = (await uploaded.json()).document_id;
  const extraction = await request.post(`${base}/documents/${doc}/extraction`);
  expect(extraction.status()).toBe(202);
  const job = (await extraction.json()).job_id;
  await expect.poll(async () => (await (await request.get(`/api/offline/jobs/${job}`)).json()).status).toBe('completed');
  const created = await request.post(`${base}/reports`, { data: { title: 'Synthetic report', kind: 'comparison', document_ids: [doc], sections: [{ section_id: 'revenue', title: 'Revenue', question: 'Revenue' }, { section_id: 'cost', title: 'Cost', question: 'Cost' }] } });
  expect(created.status()).toBe(201);
  const first = await created.json();
  const report = `${base}/reports/${first.report_id}`;
  const citation = first.sections[0].claims[0].citations[0];
  const source = await request.get(`${base}/documents/${doc}/chunks/${citation.chunk_id}?version=${citation.version}`);
  expect(source.status()).toBe(200);
  const chunk = await source.json();
  expect(chunk.text).toContain(citation.quote);
  expect(citation.locator).toEqual(chunk.locator);
  const approved = await request.post(`${report}/revisions`, { data: { base_version: 1, sections: [], approved_section_ids: ['cost'] } });
  expect(approved.status()).toBe(201);
  const second = await approved.json();
  expect(second.sections[1].approved).toBe(true);
  const revision = await request.post(`${report}/revisions`, { data: { base_version: 2, sections: [{ section_id: 'revenue', title: 'Revised revenue', question: 'Revenue credits' }] } });
  expect(revision.status()).toBe(201);
  const third = await revision.json();
  expect(third.version).toBe(3);
  expect(third.sections[1]).toEqual(second.sections[1]);
  expect(third.sections[0].origin_version).toBe(3);
  expect(await (await request.get(`${report}/versions/1`)).json()).toEqual(first);
  expect((await (await request.get(`${report}/versions`)).json()).map((r: { version: number }) => r.version)).toEqual([1, 2, 3]);
  const markdown = await request.get(`${report}/versions/1/markdown`);
  expect(markdown.status()).toBe(200);
  expect(markdown.headers()['content-disposition']).toBe('attachment; filename="report.md"');
  expect(await markdown.text()).toContain('Revenue');
  const other = await request.post('/api/offline/workspaces', { data: { name: 'Other synthetic workspace' } });
  const otherId = (await other.json()).workspace_id;
  expect((await request.get(`/api/offline/workspaces/${otherId}/reports/${first.report_id}`)).status()).toBe(404);
});
